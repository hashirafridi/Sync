package com.hashir.sync.data.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.datastore.preferences.preferencesDataStore
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.flow.first
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.inject.Inject
import javax.inject.Singleton

private val Context.tokenDataStore: DataStore<Preferences> by preferencesDataStore(
    name = "secure_tokens",
)

/**
 * Access tokens, encrypted at rest with a key that never leaves the device's hardware
 * keystore.
 *
 * Tokens are kept out of Room entirely. A Room database is a plain file: readable on a
 * rooted device, and liable to be swept into backups. A Page token that never expires is
 * effectively a permanent key to publish on someone's Page, so it gets the same treatment
 * a password would.
 *
 * `androidx.security:security-crypto` (EncryptedSharedPreferences) is deliberately not
 * used -- it has been deprecated and unmaintained, so the AES-GCM wrapping is done
 * directly against the Android Keystore here.
 */
@Singleton
class EncryptedTokenStore @Inject constructor(
    @ApplicationContext private val context: Context,
) {

    suspend fun putUserToken(fbUserId: String, token: String) =
        put(userTokenKey(fbUserId), token)

    suspend fun getUserToken(fbUserId: String): String? = get(userTokenKey(fbUserId))

    suspend fun putPageToken(pageId: String, token: String) = put(pageTokenKey(pageId), token)

    suspend fun getPageToken(pageId: String): String? = get(pageTokenKey(pageId))

    /**
     * Wipes an account's user token along with the Page tokens belonging to it.
     *
     * The caller supplies the Page ids because this store has no notion of which Page
     * belongs to which account -- that relationship lives in Room, and duplicating it
     * here would be one more thing to keep in sync.
     */
    suspend fun removeAccount(fbUserId: String, pageIds: List<String>) {
        context.tokenDataStore.edit { prefs ->
            prefs.remove(userTokenKey(fbUserId))
            pageIds.forEach { prefs.remove(pageTokenKey(it)) }
        }
    }

    suspend fun clearAll() {
        context.tokenDataStore.edit { it.clear() }
    }

    private suspend fun put(key: Preferences.Key<String>, value: String) {
        val encrypted = encrypt(value)
        context.tokenDataStore.edit { it[key] = encrypted }
    }

    private suspend fun get(key: Preferences.Key<String>): String? {
        val stored = context.tokenDataStore.data.first()[key] ?: return null
        return runCatching { decrypt(stored) }.getOrNull()
        // A decrypt failure means the keystore key is gone -- app data cleared, device
        // restored from backup, or the key invalidated. Returning null rather than
        // throwing lets the caller treat it as "needs reconnect", which is exactly what
        // it is, instead of crashing on launch.
    }

    // --- crypto ------------------------------------------------------------------

    private fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())

        // A fresh random IV per encryption, generated by the provider. It is not secret
        // and is prepended to the ciphertext so decryption can recover it.
        val iv = cipher.iv
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))

        return android.util.Base64.encodeToString(
            iv + ciphertext,
            android.util.Base64.NO_WRAP,
        )
    }

    private fun decrypt(encoded: String): String {
        val bytes = android.util.Base64.decode(encoded, android.util.Base64.NO_WRAP)
        require(bytes.size > IV_LENGTH) { "stored token is too short to contain an IV" }

        val iv = bytes.copyOfRange(0, IV_LENGTH)
        val ciphertext = bytes.copyOfRange(IV_LENGTH, bytes.size)

        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), GCMParameterSpec(TAG_LENGTH_BITS, iv))

        return String(cipher.doFinal(ciphertext), Charsets.UTF_8)
    }

    /**
     * Fetches the keystore key, generating it on first use.
     *
     * The key material is held by the Android Keystore and never enters this process --
     * the app can ask it to encrypt and decrypt, but cannot read the key itself. On
     * devices with a secure element it is backed by hardware.
     */
    private fun secretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                // No user-authentication requirement on purpose: uploads run from
                // background workers, which cannot prompt for a fingerprint.
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    private fun userTokenKey(fbUserId: String) = stringPreferencesKey("user_token_$fbUserId")

    private fun pageTokenKey(pageId: String) = stringPreferencesKey("page_token_$pageId")

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "fb_token_key"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_SIZE_BITS = 256

        /** GCM standard nonce length. */
        const val IV_LENGTH = 12
        const val TAG_LENGTH_BITS = 128
    }
}
